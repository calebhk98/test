"""Render Obsidian-compatible markdown pages.

Frontmatter values are written as JSON scalars and lists, which are valid
YAML, so Obsidian, Dataview and plain scripts all read them.
"""
from __future__ import annotations

import json
import re
import unicodedata
from pathlib import Path

from ..models import Enrichment, Section, Transcript, VideoInfo

AGENTS_MD = """# How to use this wiki (for AI agents)

This folder is generated by agent-wiki. Each video has a page in `videos/`,
and each chapter of a video has its own page in `sections/<video_id>/`.
Section pages are the useful unit: one topic, its summary, extracted facts
(model sizes, licence, censorship, hardware), source links, a timestamped
link and the transcript. Do not edit pages by hand; they are rewritten.

Run commands from the folder that holds config.toml, or add `--root <folder>`.
Add `--json` (anywhere on the line) for machine-readable output.

## Find things

    agentwiki search "open weights text to video model" --kind section
    agentwiki search "model sizes" --tag text-to-video --since 2026-06-01
    agentwiki ask "what are good text to video models, how big are they"
    agentwiki show <doc_id | video id | URL | title>

Results are ranked by relevance, not date. AI news ages fast: check the
`published` date, and cite the section's timestamped `url`.

## Add things

    agentwiki add <URL, id, or title>        one video, processed now
    agentwiki add <...> --queue-only         queued for the next `run`
    agentwiki channel add <URL or @handle>   subscribe; queues recent uploads
    agentwiki channel add <...> --backfill   ...and every past upload
    agentwiki backfill <channel>             queue a subscribed channel's history
    agentwiki run --max-minutes 60           process the queue
    agentwiki status --list queued           what is waiting, with ids and titles

A title only works for videos the catalog already knows (after `channel
add`, `check` or `backfill`); otherwise use the URL. Processing takes minutes
per video (download, then transcription, the slow step), so for many videos
queue them and let `run` work through them, in the background or on a timer,
instead of waiting on `add`.

## Statuses

queued (waiting), processing, done, failed (retried by `run` a few times),
skipped (filtered out on purpose: a Short, a live stream, or set aside).
`add <id>` brings back a failed or skipped video; `backfill` never re-adds
videos it has already seen. A done video can show as queued again when
`run` is redoing its tags and summaries with a model that is now available.
"""


def slugify(text: str, limit: int = 60) -> str:
    text = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return (slug[:limit].rstrip("-")) or "untitled"


def hms(seconds: float) -> str:
    whole_seconds = int(seconds)
    hours, remainder = divmod(whole_seconds, 3600)
    minutes, seconds_part = divmod(remainder, 60)
    return f"{hours}:{minutes:02d}:{seconds_part:02d}" if hours else f"{minutes}:{seconds_part:02d}"


def frontmatter(fields: dict) -> str:
    lines = ["---"]
    for key, value in fields.items():
        if value is None or value == "" or value == []:
            continue
        lines.append(f"{key}: {json.dumps(value, ensure_ascii=False)}")
    lines.append("---")
    return "\n".join(lines)


def _md_text(text: str) -> str:
    """Keep transcript text from turning into headings, tags or wikilinks."""
    text = text.replace("[[", "[ [").replace("]]", "] ]")
    return re.sub(r"(^|\s)#(?=\w)", r"\1\\#", text)


def _paragraphs(text: str, sentences: int = 5) -> str:
    parts = re.split(r"(?<=[.!?])\s+", text.strip())
    if len(parts) < 3:  # caption text with no punctuation: break on length instead
        words = text.split()
        return "\n\n".join(" ".join(words[start:start + 120]) for start in range(0, len(words), 120))
    return "\n\n".join(" ".join(parts[start:start + sentences]) for start in range(0, len(parts), sentences))


def _tags_inline(tags: list[str]) -> str:
    return " ".join(f"#{tag}" for tag in tags)


class WikiWriter:
    def __init__(self, wiki_dir: Path):
        self.wiki_dir = Path(wiki_dir)

    # ---- paths (wiki-relative, no extension, as Obsidian links them) --------

    def video_path(self, video_info: VideoInfo) -> str:
        date = (video_info.published or "")[:10] or "undated"
        return f"videos/{date}-{slugify(video_info.title)}-{video_info.video_id}"

    def section_path(self, video_info: VideoInfo, section: Section) -> str:
        return f"sections/{video_info.video_id}/{section.index:02d}-{slugify(section.title)}"

    def channel_path(self, channel: str) -> str:
        return f"channels/{slugify(channel or 'unknown')}"

    @staticmethod
    def link(path: str, label: str, in_table: bool = False) -> str:
        # Inside a table Obsidian needs the alias pipe escaped or it splits the cell.
        separator = "\\|" if in_table else "|"
        return f"[[{path}{separator}{label.replace('|', '-').replace(']', ')')}]]"

    def _write(self, relative_path: str, text: str) -> Path:
        path = self.wiki_dir / f"{relative_path}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    # ---- pages -------------------------------------------------------------

    def write_agents_md(self) -> None:
        agents_path = self.wiki_dir / "AGENTS.md"
        if not agents_path.exists():
            self.wiki_dir.mkdir(parents=True, exist_ok=True)
            agents_path.write_text(AGENTS_MD, encoding="utf-8")

    def remove_video(self, video_id: str) -> None:
        for page_path in (self.wiki_dir / "videos").glob(f"*-{video_id}.md"):
            page_path.unlink()
        section_dir = self.wiki_dir / "sections" / video_id
        if section_dir.is_dir():
            for page_path in section_dir.glob("*.md"):
                page_path.unlink()
            section_dir.rmdir()

    def write_video(self, video_info: VideoInfo, transcript: Transcript, sections: list[Section],
                    video_enrichment: Enrichment, *, transcriber: str, enricher: str) -> str:
        self.write_agents_md()          # however the wiki was created, agents find their guide
        # Titles and chapters can change between runs; never leave orphan pages.
        self.remove_video(video_info.video_id)
        video_page_path = self.video_path(video_info)
        for position, section in enumerate(sections):
            previous_section = sections[position - 1] if position > 0 else None
            next_section = sections[position + 1] if position + 1 < len(sections) else None
            self._write(self.section_path(video_info, section),
                        self._section_page(video_info, section, video_page_path,
                                           previous_section, next_section))
        self._write(video_page_path, self._video_page(video_info, transcript, sections, video_enrichment,
                                                      transcriber, enricher))
        return video_page_path

    def _video_page(self, video_info, transcript, sections, enrichment: Enrichment,
                    transcriber, enricher) -> str:
        frontmatter_text = frontmatter({
            "title": video_info.title, "aliases": [video_info.title], "type": "video",
            "video_id": video_info.video_id, "url": video_info.url, "channel": video_info.channel,
            "channel_url": video_info.channel_url, "published": video_info.published,
            "duration": hms(video_info.duration), "tags": enrichment.tags, "sections": len(sections),
            "transcriber": transcriber, "enricher": enricher,
        })
        out = [frontmatter_text, f"# {video_info.title}", "",
               f"[{'Watch on YouTube' if 'youtube.com/' in video_info.url else 'Original'}]"
               f"({video_info.url}) | "
               f"{self.link(self.channel_path(video_info.channel), video_info.channel or 'channel')}"
               f" | {video_info.published[:10]} | {hms(video_info.duration)}", ""]
        if enrichment.summary:
            out += ["## Summary", "", enrichment.summary, ""]
        if sections:
            out += ["## Sections", "", "| # | Time | Section | Tags |", "| --- | --- | --- | --- |"]
            for section in sections:
                label = section.title + (" (sponsor)" if section.is_sponsor else "")
                out.append(f"| {section.index} | "
                           f"[{hms(section.start)}]({video_info.timestamp_url(section.start)}) | "
                           f"{self.link(self.section_path(video_info, section), label, in_table=True)} | "
                           f"{_tags_inline(section.tags[:5])} |")
            out.append("")
        if video_info.description:
            quoted = "\n".join("> " + _md_text(line) if line.strip() else ">"
                               for line in video_info.description.splitlines())
            out += ["## Description", "", quoted, ""]
        out += ["## Transcript", ""]
        for section in sections:
            out += [f"### [{hms(section.start)}]({video_info.timestamp_url(section.start)}) "
                    f"{section.title}", "",
                    _paragraphs(_md_text(section.text)), ""]
        if not sections:
            out += [_paragraphs(_md_text(transcript.text)), ""]
        return "\n".join(out)

    def _section_page(self, video_info, section: Section, video_page_path, previous_section,
                      next_section) -> str:
        frontmatter_text = frontmatter({
            "title": section.title, "type": "section", "video_id": video_info.video_id,
            "section": section.index, "start": round(section.start), "end": round(section.end),
            "url": video_info.timestamp_url(section.start),
            "video": f"[[{video_page_path}]]", "channel": video_info.channel,
            "published": video_info.published,
            "tags": section.tags, "sponsor": section.is_sponsor or None,
        })
        nav = []
        if previous_section:
            nav.append("prev: " + self.link(self.section_path(video_info, previous_section),
                                            previous_section.title))
        if next_section:
            nav.append("next: " + self.link(self.section_path(video_info, next_section), next_section.title))
        out = [frontmatter_text, f"# {section.title}", "",
               f"Part {section.index} of {self.link(video_page_path, video_info.title)}",
               f"[Watch {hms(section.start)} to {hms(section.end)}]"
               f"({video_info.timestamp_url(section.start)}) | {video_info.published[:10]}",
               ""]
        if nav:
            out += [" | ".join(nav), ""]
        if section.summary:
            out += ["## Summary", "", section.summary, ""]
        if section.facts:
            out += ["## Facts", ""] + [f"- {fact}" for fact in section.facts] + [""]
        if section.links:
            out += ["## Links", ""] + [f"- [{link.label}]({link.url})" for link in section.links] + [""]
        out += ["## Transcript", "", _paragraphs(_md_text(section.text)), ""]
        return "\n".join(out)

    def write_channel(self, channel: str, channel_url: str, videos: list[tuple[str, str, str]]) -> None:
        """videos: (published, title, wiki path), any order."""
        out = [frontmatter({"title": channel, "type": "channel", "url": channel_url}),
               f"# {channel}", ""]
        if channel_url:
            out += [f"[Channel on YouTube]({channel_url})", ""]
        out += [f"{len(videos)} videos in the wiki.", ""]
        for published, title, path in sorted(videos, reverse=True):
            out.append(f"- {published[:10]} {self.link(path, title)}")
        self._write(self.channel_path(channel), "\n".join(out) + "\n")
